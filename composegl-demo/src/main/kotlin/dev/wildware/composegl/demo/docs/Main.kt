/**
 * Takes every picture in the wiki.
 *
 * `./gradlew :composegl-demo:docShots` writes them to `docs/wiki/images`. One hidden window, one
 * canvas, one skin, and a fresh interface per picture — so a picture is a photograph of the real
 * toolkit rather than a drawing of it, and the whole set is regenerated by one command when
 * something changes shape.
 *
 * Each picture is drawn in the bottom-left corner of the window at its own size and only that
 * rectangle is read back, which is the same trick the golden screenshots use.
 */
fun main() {
    val out = File(System.getenv("COMPOSEGL_DOC_SHOTS") ?: "docs/wiki/images")
    out.mkdirs()

    val window = GlfwWindow("composegl doc shots", Window, Window, visible = false, vsync = false)
    val fonts = StbFonts(pageSize = 1024)
    val typeface = resource("fonts/DejaVuSans.ttf")
    // Every size again at 125% and 150%, for the picture of the text size setting.
    fonts.register("body", typeface, scaledTextSizes(listOf(12, 13, 16, 20), listOf(1f, 1.25f, 1.5f)))
    fonts.register("display", typeface, listOf(34))
    // What the toolkit's own skin asks for, for the pictures taken without the example's skin.
    fonts.register("default", typeface, listOf(12, 13, 14, 16, 18, 22, 26))
    // Where characters DejaVu does not have come from, for the chat picture. Small cuts of Noto
    // Sans CJK holding only what that picture says, and Noto's emoji as pictures, at every size any
    // family above is asked for.
    val everySize = fonts.families().flatMap { fonts.sizesOf(it) }.distinct()
    fonts.register(
        "cjk",
        resource("fonts/NotoSansSC-Subset.ttf"),
        everySize,
        StbFonts.codepointsOf("你好！欢迎来到游戏玩家プレイヤーこんにちは"),
    )
    fonts.register("korean", resource("fonts/NotoSansKR-Subset.ttf"), everySize, StbFonts.codepointsOf("플레이어안녕하세요"))
    fonts.registerPictures(
        "emoji",
        mapOf(
            "👍" to resource("emoji/emoji_u1f44d.png"),
            "🎮" to resource("emoji/emoji_u1f3ae.png"),
            "😀" to resource("emoji/emoji_u1f600.png"),
            "❤️" to resource("emoji/emoji_u2764.png"),
            "🚀" to resource("emoji/emoji_u1f680.png"),
            "🔥" to resource("emoji/emoji_u1f525.png"),
        ),
        everySize,
    )
    fonts.fallBackTo(listOf("cjk", "korean", "emoji"))

    val art = GlTexture.decode(resource("ui/ui.png"))
    val coins = coinSheet()
    val canvas = GlCanvas(fonts)
    val skin = demoSkin(atlas(art, coins), fonts)

    try {
        docShots().forEach { shot ->
            val file = File(out, "${shot.name}.png")
            save(file, take(shot, canvas, fonts, if (shot.stock) Skin.Default else skin.skin))
            println("wrote ${file.path}")
        }
    } finally {
        canvas.close()
        coins.close()
        art.close()
        fonts.close()
        window.close()
    }
}

/**
 * The art the skin file names, by region.
 *
 * The same three regions the example uses, because the pictures are taken through the example's
 * skin: what the wiki shows is what somebody running `:composegl-demo:runGl` sees.
 */
private fun atlas(art: GlTexture, coins: GlTexture) = ArtAtlas.of(
    mapOf(
        "panel" to art.region(0, 0, 48, 48),
        "ribbon" to art.region(52, 0, 24, 24),
        "icon/crest" to art.region(80, 0, 24, 24),
    ) + (0 until CoinFrames).associate { "coin_$it" to coins.region(it * CoinSize, 0, CoinSize, CoinSize) },
)

private const val CoinFrames = 8
private const val CoinSize = 32

/**
 * A coin turning on its edge, as one sheet of [CoinFrames] frames side by side.
 *
 * Drawn here rather than shipped as a picture so the sprite-animation shot has a real sheet to cut
 * up without adding art to the example: each frame is the coin squashed by how far it has turned,
 * with a darker back face and a rim.
 */
private fun coinSheet(): GlTexture {
    val width = CoinFrames * CoinSize
    val pixels = ByteArray(width * CoinSize * 4)
    val radius = 13f
    val centre = (CoinSize - 1) / 2f
    for (frame in 0 until CoinFrames) {
        val turn = kotlin.math.cos(frame * Math.PI / CoinFrames * 2).toFloat()
        val across = (radius * kotlin.math.abs(turn)).coerceAtLeast(2f)
        val face = if (turn >= 0f) 0xF2C14E else 0xC9952E
        for (y in 0 until CoinSize) {
            for (x in 0 until CoinSize) {
                val dx = x - centre
                val dy = y - centre
                if ((dx / across) * (dx / across) + (dy / radius) * (dy / radius) > 1f) continue
                val innerAcross = (across - 2f).coerceAtLeast(0.5f)
                val rim = (dx / innerAcross) * (dx / innerAcross) + (dy / (radius - 2f)) * (dy / (radius - 2f)) > 1f
                val shine = turn >= 0f && !rim && dx < -across * 0.2f && dx > -across * 0.5f
                val colour = when {
                    rim -> 0x8A5A12
                    shine -> 0xFFE9A8
                    else -> face
                }
                val at = (y * width + frame * CoinSize + x) * 4
                pixels[at] = (colour shr 16).toByte()
                pixels[at + 1] = (colour shr 8).toByte()
                pixels[at + 2] = colour.toByte()
                pixels[at + 3] = 0xFF.toByte()
            }
        }
    }
    return GlTexture.rgba(width, CoinSize, pixels, smooth = false)
}

private fun resource(path: String): ByteArray =
    checkNotNull(object {}.javaClass.classLoader.getResourceAsStream(path)) { "no $path on the classpath" }
        .use { it.readBytes() }

/** The window every picture is drawn inside. Bigger than the biggest of them. */
private const val Window = 640

/** Frames drawn before the shutter, so that anything with a first-frame animation has settled. */
private const val Settle = 3

/** How many moves a doc shot's drag is made of. */
private const val DragSteps = 12

/** Sixty a second, which is the rate every animation in the toolkit is written against. */
private const val FrameNanos = 16_666_666L

private fun take(shot: DocShot, canvas: GlCanvas, fonts: FontProvider, skin: Skin): BufferedImage {
    val window = Size(shot.width.toFloat(), shot.height.toFloat())
    // One player is an ordinary picture; several share the window the way a local co-op game does.
    val viewports = if (shot.players == 1) {
        listOf(Viewport(design = window, physical = window, policy = ScalePolicy.Fit))
    } else {
        Viewport.splitScreen(
            design = Size(shot.width.toFloat() / 2f, shot.height.toFloat()),
            physical = window,
            players = shot.players,
        )
    }

    val hosts = viewports.map { UiHost() }

    // Real input rather than a widget told to look hovered: a picture of a hover is only worth
    // having if it is the state the toolkit actually reaches when a mouse is there.
    val focuses = hosts.map { FocusManager(it.root) }
    val pointers = hosts.indices.map { PointerRouter(hosts[it].root, focuses[it]) }
    val pads = focuses.map { GamepadNavigator(it) }
    val mouse = pointers[0]

    // The same for a pad's cursor: a real one, moved and framed as a game would, on a player who is
    // on a pad — which is the only time the arrow is drawn.
    val cursor = GamepadCursor(hosts[0].root, mouse)

    hosts.forEachIndexed { player, host ->
        host.setContent {
            CompositionLocalProvider(LocalFonts provides fonts, LocalDocPlayer provides player) {
                ProvideSkin(skin) {
                    if (shot.padCursor == null || player != 0) {
                        shot.content()
                    } else {
                        ProvideInputSource(InputSourceTracker(InputSource.Gamepad)) {
                            ProvideGamepadCursor(cursor) { shot.content() }
                        }
                    }
                }
            }
        }
    }

    // Each player's pad through one router, as a split-screen game has it: pad 0 is player one's.
    val router = InputRouter()
    hosts.indices.forEach { player ->
        router.assignGamepad(GamepadId(player), object : InputSink {
            override fun onPointer(event: PointerEvent) = pointers[player].onPointer(event)
            override fun onKey(event: KeyEvent) = false
            override fun onText(event: TextEvent) = false
            override fun onGamepad(event: GamepadEvent) = pads[player].onGamepad(event)
        })
    }

    val renderers = hosts.indices.map { player ->
        // Focus is drawn only where a pad moved it: the split-screen picture is about whose focus
        // is where, and every other picture shows its widgets the way they look before anyone
        // reaches for a pad.
        UiRenderer(hosts[player], canvas, shot.budget?.takeIf { player == 0 } ?: FrameBudget()).also { if (shot.players > 1) it.focus = focuses[player] }
    }
    // After layout, because a pointer lands on whatever is under it and nothing is anywhere until
    // the tree has been measured.
    var dragged = false
    var clicked = false
    renderers[0].onLaidOut = { nanos ->
        shot.padCursor?.let { at ->
            cursor.moveTo(at)
            cursor.frame(nanos / 1_000_000L)
        }
        val to = shot.dragTo
        shot.pointer?.let { at ->
            if (to == null) {
                mouse.onPointer(PointerEvent.Move(PointerId.Mouse, at))
                if (shot.press) mouse.onPointer(PointerEvent.Press(PointerId.Mouse, at))
                // Once, not every frame: a click every frame on a dropdown opens and closes it in turn.
                if (shot.click && !clicked) {
                    clicked = true
                    mouse.onPointer(PointerEvent.Press(PointerId.Mouse, at))
                    mouse.onPointer(PointerEvent.Release(PointerId.Mouse, at))
                }
            } else if (!dragged) {
                // Once, in steps, the way a hand does it: a drag is a gesture rather than a state,
                // and pressing again every frame would be a new one each time.
                dragged = true
                mouse.onPointer(PointerEvent.Press(PointerId.Mouse, at))
                for (step in 1..DragSteps) {
                    val along = at + (to - at) * (step / DragSteps.toFloat())
                    mouse.onPointer(PointerEvent.Move(PointerId.Mouse, along, setOf(PointerButton.Primary)))
                }
                // Held, for a picture of something still being carried.
                if (!shot.hold) mouse.onPointer(PointerEvent.Release(PointerId.Mouse, to))
            }
        }
    }

    try {
        val frames = Settle + (shot.seconds * 60f).toInt()
        for (frame in 0..frames) {
            GL11.glClearColor(0f, 0f, 0f, 1f)
            GL11.glClear(GL11.GL_COLOR_BUFFER_BIT)
            renderers.forEachIndexed { player, ui -> ui.render(viewports[player], frame * FrameNanos) }
            // Once focus has settled on something, so a step moves it from somewhere.
            if (frame == 1) {
                shot.pads.forEach { (pad, button) ->
                    router.onGamepad(GamepadEvent.ButtonDown(pad, button))
                    router.onGamepad(GamepadEvent.ButtonUp(pad, button))
                }
            }
        }
        return read(shot.width, shot.height)
    } finally {
        hosts.forEach { it.dispose() }
    }
}

/** The bottom-left corner of the framebuffer, turned the right way up. */
private fun read(width: Int, height: Int): BufferedImage {
    val bytes = BufferUtils.createByteBuffer(width * height * 4)
    GL11.glReadPixels(0, 0, width, height, GL11.GL_RGBA, GL11.GL_UNSIGNED_BYTE, bytes)

    val image = BufferedImage(width, height, BufferedImage.TYPE_INT_RGB)
    for (y in 0 until height) {
        for (x in 0 until width) {
            // OpenGL hands back the bottom row first.
            val at = ((height - 1 - y) * width + x) * 4
            image.setRGB(
                x,
                y,
                (bytes.get(at).toInt() and 0xFF shl 16) or
                    (bytes.get(at + 1).toInt() and 0xFF shl 8) or
                    (bytes.get(at + 2).toInt() and 0xFF),
            )
        }
    }
    return image
}

private fun save(file: File, image: BufferedImage) {
    ImageIO.write(image, "png", file)
}
